// 词典以中文原文为键：中文（默认）直接回原文，其它语言查 EN。
// vars 用于 {name} 占位符（外壳只有中英两套，数词变化在 studioCount / studioPoint /
// studioRecords 这类小函数里处理，不做 ICU 复数）。
export function translateShellText(value, lang = 'zh', vars) {
  const text = lang === 'en' ? EN[value] || value : value
  if (!vars || typeof text !== 'string') return text
  return text.replace(/\{(\w+)\}/g, (token, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : token))
}

// 历史记录的总条数与页码：英文要按单复数分叉，没法塞进一张平面表。
export function studioRecords(value, lang = 'zh') {
  return lang === 'en' ? `${value} ${Number(value) === 1 ? 'record' : 'records'}` : `共 ${value} 条`
}

export function studioPage(page, total, lang = 'zh') {
  return lang === 'en' ? `Page ${page} / ${total}` : `第 ${page} / ${total} 页`
}

export function studioCount(value, lang = 'zh') {
  return lang === 'en' ? `${value} ${Number(value) === 1 ? 'image' : 'images'}` : `${value} 张`
}

// 积分数值的「数字」和「单位」分开给：余额那种大数字 + 小单位的排版要拆开摆。
export function studioPointParts(value, lang = 'zh') {
  // 积分按一/两位小数结算，浮点累加会出现 4.800000000000001 这类尾差，展示前统一收敛。
  const number = Number(value)
  const shown = Number.isFinite(number) ? Math.round(number * 100) / 100 : value
  return {
    value: String(shown),
    unit: lang === 'en' ? (Number(shown) === 1 ? 'credit' : 'credits') : '积分',
  }
}

export function studioPoint(value, lang = 'zh') {
  const { value: amount, unit } = studioPointParts(value, lang)
  return `${amount} ${unit}`
}
